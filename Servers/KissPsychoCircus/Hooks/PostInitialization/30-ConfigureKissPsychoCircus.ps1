#Requires -Modules Logging

# Configure the Kiss: Psycho Circus dedicated server from the KPC_* settings:
#   <KPC_CONFIG>                 server variables ("name" "value" lines), loaded with -exec
#   MapLists/lancommander.txt    the map rotation (KPC_MAPS)
#   Dedicated-lancommander.exe   Dedicated.exe patched to sleep between frames (KPC_IDLE_PATCH)
#
# Everything is written through the merged view, so it lands in Overlay/ and Server/ stays as
# installed. The config is regenerated on every start as long as its first line is the marker
# below; a config without it (your own) is left alone.

$marker  = '// Generated by LANCommander from the KPC_* settings; delete this line to keep your edits'
$config  = if ($Env:KPC_CONFIG) { $Env:KPC_CONFIG } else { 'lancommander.cfg' }
$cfgPath = Join-Path $Env:SERVER_ROOT $config

function ConvertTo-Bool([string] $Value) {
    $Value.ToLower() -in @('true', '1', 'yes', 'on')
}

# ---------------------------------------------------------------------------------------------
# Idle patch
#
# Dedicated.exe's main loop runs the server every 8 ms and polls the console in between without
# ever sleeping. Under Wine every poll is a wineserver round trip, so an idle server burns about
# 1.7 cores. The patch (for the retail 1.13 Dedicated.exe only) jumps from that loop into a code
# cave at the end of .text that calls Sleep() for the rest of the 8 ms frame. Sleep is looked up
# once with GetModuleHandleA/GetProcAddress and cached in .data. Idle CPU drops to about 20%.
# ---------------------------------------------------------------------------------------------
$original = Join-Path $Env:SERVER_ROOT 'Dedicated.exe'
$patched  = Join-Path $Env:SERVER_ROOT 'Dedicated-lancommander.exe'

$knownSha256   = '19D7766C949B2278EC1E99C9E559312D35FD26456BB2539D9E525ABAD8A829A8'  # v1.13 (build 113)
$patchedSha256 = 'B585917F8831DA7F13B30C38F3EEA8479A966E7CF65E8373D2D7393F6AB980BD'

Remove-Item -Path $patched -Force -ErrorAction SilentlyContinue

if ((ConvertTo-Bool "$Env:KPC_IDLE_PATCH") -and (Test-Path -Path $original)) {
    $hash = (Get-FileHash -Path $original -Algorithm SHA256).Hash
    if ($hash -ne $knownSha256) {
        Write-Log -Level Warning "Dedicated.exe is not the known 1.13 build (sha256 $hash); running it unpatched, which uses a lot of CPU"
    } else {
        $bytes = [System.IO.File]::ReadAllBytes($original)

        function Set-Bytes([int] $Offset, [string] $Hex) {
            $data = [System.Convert]::FromHexString($Hex)
            [System.Array]::Copy($data, 0, $bytes, $Offset, $data.Length)
        }

        # Code cave at 0x40E310 (file offset 0xE310, zero padding at the end of .text):
        #   cmp ecx,8 / jae update / mov eax,[0x41AC98] / test eax,eax / jnz sleep
        #   push "KERNEL32.dll" / call [GetModuleHandleA] / push "Sleep" / push eax
        #   call [GetProcAddress] / mov [0x41AC98],eax
        #   sleep: mov edx,edi / sub edx,esi / add edx,8 / push edx / call eax / jmp 0x401DE3
        #   update: jmp 0x401E11 / "Sleep\0"
        Set-Bytes 0xE310 ('83f9087334a198ac410085c0751c68a4f84000ff15a4f04000684ee3400050ff1504f04000' +
                          'a398ac41008bd72bd683c20852ffd0e99a3affffe9c33affff536c65657000')
        # 0x401E0C: "cmp ecx,8 / jb 0x401DE3" -> "jmp 0x40E310"
        Set-Bytes 0x1E0C 'e9ffc40000'
        # .text VirtualSize 0xD308 -> 0xD400 (covers the cave), .data VirtualSize 0xAC98 -> 0xACA0
        # (covers the cached Sleep pointer)
        Set-Bytes 0x1F0 '00d40000'
        Set-Bytes 0x240 'a0ac0000'

        [System.IO.File]::WriteAllBytes($patched, $bytes)
        $hash = (Get-FileHash -Path $patched -Algorithm SHA256).Hash
        if ($hash -ne $patchedSha256) {
            Remove-Item -Path $patched -Force
            throw "Patched Dedicated.exe has an unexpected sha256 ($hash)"
        }
        chown "$($Env:UID):$($Env:GID)" $patched
        Write-Log "Wrote Dedicated-lancommander.exe (idle patch)"
    }
}

# ---------------------------------------------------------------------------------------------
# Server config
# ---------------------------------------------------------------------------------------------
if ((Test-Path -Path $cfgPath) -and ((Get-Content -Path $cfgPath -TotalCount 1) -ne $marker)) {
    Write-Log "$config is not managed by this image; using it as is"
    return
}

# Map rotation: bare names are deathmatch worlds (PM01 -> worlds\deathmatch\PM01)
$maps = @("$Env:KPC_MAPS" -split '[,;\s]+' | Where-Object { $_ } | ForEach-Object {
    $map = $_.Replace('/', '\') -replace '\.dat$', ''
    if ($map -notmatch '\\') { $map = "worlds\deathmatch\$map" }
    $map
})
if (-not $maps) { throw 'KPC_MAPS is empty' }

$mapListDir = Join-Path $Env:SERVER_ROOT 'MapLists'
New-Item -ItemType Directory -Path $mapListDir -Force | Out-Null
$mapList = Join-Path $mapListDir 'lancommander.txt'
[System.IO.File]::WriteAllText($mapList, (($maps -join "`r`n") + "`r`n"))

$gameTypes = @{ 'deathmatch' = '1'; 'dm' = '1'; 'conquer' = '2'; 'bighead' = '2'; 'bigheads' = '2' }
$gameType  = "$Env:KPC_GAME_TYPE".ToLower()
if ($gameTypes.ContainsKey($gameType)) {
    $gameType = $gameTypes[$gameType]
} elseif ($gameType -and $gameType -notmatch '^[12]$') {
    throw "Unknown KPC_GAME_TYPE '$Env:KPC_GAME_TYPE' (deathmatch or conquer)"
}

$maxPlayers = "$Env:KPC_MAX_PLAYERS"
if ($maxPlayers -and ([int] $maxPlayers -lt 1 -or [int] $maxPlayers -gt 16)) {
    throw "KPC_MAX_PLAYERS must be between 1 and 16"
}

# name, value
$settings = [ordered] @{
    'hostname'     = $Env:KPC_HOSTNAME
    'location'     = $Env:KPC_LOCATION
    'motd'         = $Env:KPC_MOTD
    'port'         = $Env:KPC_PORT
    'gamespy_port' = $Env:KPC_GAMESPY_PORT
    'maplist'      = 'maplists\\lancommander.txt'  # escaped like the stock server.cfg
    'maxclients'   = $maxPlayers
    'gametype'     = $gameType
    'teamplay'     = $Env:KPC_TEAMPLAY
    'fraglimit'    = $Env:KPC_FRAG_LIMIT
    'timelimit'    = $Env:KPC_TIME_LIMIT
    'spawntype'    = $Env:KPC_SPAWN_TYPE
    'friendlykill' = $Env:KPC_FRIENDLY_KILL
    'suicide'      = $Env:KPC_SUICIDE
    'keepitems'    = $Env:KPC_KEEP_ITEMS
    'fovchange'    = $Env:KPC_FOV_CHANGE
    'gibdetail'    = $Env:KPC_GIB_DETAIL
}

$lines = @($marker)
foreach ($name in $settings.Keys) {
    $value = "$($settings[$name])"
    if ($value -eq '') { continue }
    $lines += '"{0}" "{1}"' -f $name, $value.Replace('"', "'")
}

# KPC_EXTRA_SETTINGS: more variables, "name value" pairs separated by ';' or new lines, e.g.
# "startgauntlets 1; startscourge 1"
foreach ($entry in "$Env:KPC_EXTRA_SETTINGS" -split '[;\r\n]+') {
    $entry = $entry.Trim()
    if (-not $entry) { continue }
    $name, $value = $entry -split '\s+', 2
    $lines += '"{0}" "{1}"' -f $name.Trim('"'), "$value".Trim().Trim('"')
}

[System.IO.File]::WriteAllText($cfgPath, (($lines -join "`r`n") + "`r`n"))
chown "$($Env:UID):$($Env:GID)" $cfgPath $mapList $mapListDir

Write-Log "Wrote $config ($($lines.Count - 1) settings) and MapLists/lancommander.txt ($($maps.Count) maps)"
