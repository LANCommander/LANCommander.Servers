#Requires -Modules Logging

# Write the server definition Dedicated/<VC_DED_NAME>.ded from the VC_* settings. This is the same
# file vcded's own setup dialog writes with "Save": `Key = value` lines, then one
# `Mission = <map>, <mode>, time|points, <value>` line per map in the rotation.
#
# The file is written through the merged view, so it lands in Overlay/. It is regenerated on every
# start as long as its first line is the marker comment below; a .ded without it (your own, saved
# from the setup dialog) is left alone.
#
# vcded reports a bad mission line with a modal message box ("Can't find map ...") and then waits
# forever, which is invisible in a container. The base game's map/mode pairs are checked here first.

$marker = '// Generated by the LANCommander image from the VC_* settings.'
$name   = if ($Env:VC_DED_NAME) { $Env:VC_DED_NAME } else { 'lancommander' }
$dir    = Join-Path $Env:SERVER_ROOT 'Dedicated'
$file   = Join-Path $dir "$name.ded"

if ((Test-Path -Path $file) -and ((Get-Content -Path $file -TotalCount 1) -ne $marker)) {
    Write-Log "Dedicated/$name.ded is not managed by this image; using it as is"
    return
}

function Format-Bool([string] $Value) {
    if ("$Value".ToLower() -in @('true', '1', 'yes', 'on')) { '1' } else { '0' }
}

# Map -> modes, as listed by the v1.60 setup dialog without add-ons
$baseMaps = @{
    'Ambush'     = @('RW', 'Coop')
    'Arroyo'     = @('ATG', 'CTF', 'DM', 'TDM', 'LMS')
    'Bahnar'     = @('ATG', 'RW', 'TT', 'CTF')
    'HalongPort' = @('ATG', 'CTF', 'DM', 'TDM', 'LMS')
    'NVABase'    = @('ATG', 'CTF', 'Coop', 'DM', 'RW', 'TDM', 'LMS')
    'RadioRelay' = @('ATG', 'RW', 'Coop')
    'Storm'      = @('ATG', 'Coop', 'DM', 'LMS', 'RW', 'TDM', 'TT', 'CTF')
    'WaterFall'  = @('ATG', 'CTF', 'DM', 'TDM', 'LMS')
    'Stream'     = @('ATG', 'Coop', 'DM', 'LMS', 'RW', 'TDM', 'TT', 'CTF')
}

$missions = [System.Collections.Generic.List[string]]::new()

foreach ($entry in ("$Env:VC_MISSIONS" -split '[;\r\n]+' | Where-Object { $_.Trim() })) {
    $parts = @($entry -split ',' | ForEach-Object { $_.Trim() })
    if ($parts.Count -ne 4) {
        throw "VC_MISSIONS entry '$($entry.Trim())' must be 'Map, Mode, time|points, value'"
    }

    $map, $mode, $rule, $value = $parts
    $rule = $rule.ToLower()

    if ($rule -eq 'time') {
        if ($value -match '^\d+$') { $value = "$($value):00" }
        if ($value -notmatch '^\d+:\d{2}$') { throw "Time '$value' in VC_MISSIONS must be minutes or mm:ss" }
    } elseif ($rule -eq 'points') {
        if ($value -notmatch '^\d+$') { throw "Points '$value' in VC_MISSIONS must be a number" }
    } else {
        throw "End rule '$rule' in VC_MISSIONS must be time or points"
    }

    # Map and mode names are matched case-insensitively; write the game's spelling
    $known = $baseMaps.Keys | Where-Object { $_ -eq $map } | Select-Object -First 1
    if ($known) {
        $map = $known
        $knownMode = $baseMaps[$map] | Where-Object { $_ -eq $mode } | Select-Object -First 1
        if (-not $knownMode) {
            throw "Map $map has no $mode mode (it has $($baseMaps[$map] -join ', '))"
        }
        $mode = $knownMode
    } else {
        Write-Log -Level Warning "Map '$map' is not a base Vietcong map; it must come from an add-on or user map"
    }

    $missions.Add("Mission = $map, $mode, $rule, $value")
}

if (-not $missions.Count) { throw 'VC_MISSIONS is empty' }

# The stock settings, in the order vcded saves them, with the VC_* overrides applied
$settings = [ordered]@{
    'Friendly fire'             = Format-Bool $Env:VC_FRIENDLY_FIRE
    'Auto balanced teams'       = Format-Bool $Env:VC_AUTO_BALANCE
    'Maximum players'           = $Env:VC_MAX_PLAYERS
    'Enemy camera'              = '0'
    'Internet game'             = Format-Bool $Env:VC_INTERNET_GAME
    'Hide server IP'            = '0'
    'Port number'               = $Env:VC_PORT
    'Cooperative difficulty'    = '1'
    'Player respawn method'     = '60'
    'Weapon respawn limit'      = '30'
    'Engineers'                 = '-1'
    'Medics'                    = '-1'
    'Snipers'                   = '-1'
    'Radiomans'                 = '-1'
    'MachineGunners'            = '-1'
    'ATG mission time'          = '5'
    'TT mission time'           = '0'
    'TT respawn time'           = '0'
    'CTF respawn time'          = '0'
    'Immortality after respawn' = '3'
    'Vietnam mode'              = '0'
    'Vietnam chat mode'         = '0'
    'Ammo boxes'                = '1'
    'Team kill'                 = '3'
    'Team kill ban'             = '6'
    'Ping kick'                 = '0'
    'Idle player kick'          = '10'
    'Team booby trap'           = '1'
    'Hradba enable'             = Format-Bool $Env:VC_HRADBA
    'Hradba auto update'        = Format-Bool $Env:VC_HRADBA
    'Hradba upload limit'       = '5'
    'User-map enable'           = '1'
    'User-map upload limit'     = '10'
    'Voice chat'                = $Env:VC_VOICE_CHAT
    'Change map voting'         = '1'
    'Restart map voting'        = '1'
    'Password'                  = $Env:VC_PASSWORD
    'Admin password'            = $Env:VC_ADMIN_PASSWORD
    'Server join message'       = $Env:VC_JOIN_MESSAGE
}

# VC_SETTINGS: "Key = value" pairs separated by ; or newlines, for any other .ded setting
foreach ($pair in ("$Env:VC_SETTINGS" -split '[;\r\n]+' | Where-Object { $_.Trim() })) {
    $key, $value = $pair -split '=', 2
    if ($null -eq $value) { throw "VC_SETTINGS entry '$($pair.Trim())' must be 'Key = value'" }
    $key = $key.Trim()
    $existing = $settings.Keys | Where-Object { $_ -eq $key } | Select-Object -First 1
    if (-not $existing) {
        Write-Log -Level Warning "VC_SETTINGS key '$key' is not a known .ded setting"
        $existing = $key
    }
    $settings[$existing] = $value.Trim()
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add($marker)
$lines.Add('// Delete the line above to keep your own edits.')
$lines.Add('')
$lines.Add("Server name = $Env:VC_SERVER_NAME")
$lines.Add('')
$lines.Add('//Server settings')
foreach ($key in $settings.Keys) {
    $lines.Add("$key = $($settings[$key])")
}
$lines.Add('')
$lines.Add('//List of missions')
$lines.AddRange($missions)

New-Item -ItemType Directory -Path $dir -Force | Out-Null
$crlf = "`r`n"
[System.IO.File]::WriteAllText($file, ($lines -join $crlf) + $crlf)
chown -R "$($Env:UID):$($Env:GID)" $dir

Write-Log "Generated Dedicated/$name.ded ($($missions.Count) mission(s))"
